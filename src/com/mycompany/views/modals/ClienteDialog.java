    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
        String nombre = txtNombre.getText();
        String nit = txtNIT.getText();
        String direccion = txtDireccion.getText();
        String correo = txtCorreo.getText();
        String telefono = txtTelefono.getText();
        switch (this.modo) {
            case ConsultaActionModes.CREAR:

                if (nombre.isEmpty() || nit.isEmpty() || direccion.isEmpty() || correo.isEmpty() || telefono.isEmpty()) {
                    JOptionPane.showMessageDialog(null, "No puede dejar los campos en blanco");
                    this.dispose();
                    return;

                } else {
                    this.setModal(false);
                    this.setAlwaysOnTop(false);
                    this._clienteService.crearCliente(nit, nombre, direccion, telefono, correo);
                    JOptionPane.showMessageDialog(null, "Se ha creado correctamente");
                    this.dispose();
                }
                break;
            case ConsultaActionModes.CONSULTAR:
                this.dispose();
                break;
            case ConsultaActionModes.ACTUALIZAR:
                if (nombre.isEmpty() || nit.isEmpty() || direccion.isEmpty() || correo.isEmpty() || telefono.isEmpty()) {
                    JOptionPane.showMessageDialog(null, "No puede dejar los campos en blanco");
                    this.dispose();
                    return;

                } else {
                    this.setModal(false);
                    this.setAlwaysOnTop(false);
                    this._clienteService.actualizarCliente(nit, nombre, direccion, telefono, correo);
                    JOptionPane.showMessageDialog(null, "Se ha actualizado correctamente");
                    this.dispose();
                }

        }
    }//GEN-LAST:event_btnCrearActionPerformed

