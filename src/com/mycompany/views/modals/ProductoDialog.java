    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
        Producto p = new Producto();
        String nombre = txtNombre.getText();
        String codigo = txtCodigo.getText();
        int precio_venta = (int) spnPrecioVenta.getValue();
        int precio_compra = (int) spnPrecioCompra.getValue();
        int proveedor_id = cboxProveedor.getSelectedIndex() + 1;
        int disponible = (int) spnDisponible.getValue();
        p.setCodigo(codigo);
        p.setNombre(nombre);
        p.setPrecio_Compra(precio_compra);
        p.setPrecio_Venta(precio_venta);
        p.setDisponible(disponible);
        p.setProveedor_id(proveedor_id);
        switch (this.modo) {
            case CREAR:
                if(nombre.isEmpty() || codigo.isEmpty() || precio_venta == 0 || precio_compra == 0) {
                    JOptionPane.showMessageDialog(null, "No puede dejar los campos en blanco");
                    this.dispose();
                    return;

                } else {
                    this.setModal(false);
                    this.setAlwaysOnTop(false);
                    ProductosService.Post(codigo, nombre, disponible,precio_compra, precio_venta, proveedor_id);
                    JOptionPane.showMessageDialog(null, "Se ha creado correctamente");
                    this.dispose();
                }
                break;
            case CONSULTAR:
                this.dispose();
                break;
            case ACTUALIZAR:
                if (nombre.isEmpty()  || precio_venta == 0 || precio_compra == 0) {
                    JOptionPane.showMessageDialog(null, "No puede dejar los campos en blanco");
                    this.dispose();
                    return;

                } else {
                    this.setModal(false);
                    this.setAlwaysOnTop(false);
                    ProductosService.PUT(p);
                    JOptionPane.showMessageDialog(null, "Se ha actualizado correctamente");
                    this.dispose();
                }

        }
    }//GEN-LAST:event_btnCrearActionPerformed

