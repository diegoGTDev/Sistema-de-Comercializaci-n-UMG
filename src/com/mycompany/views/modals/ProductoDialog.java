    public ProductoDialog(java.awt.Frame parent, boolean modal, Producto producto, ConsultaActionModes modo) {
        super(parent, modal);
        initComponents();
        this.modo = (modo != null) ? modo : null;
        codigoPH = this.txtCodigo.getText();
        nombrePH = this.txtNombre.getText();
        cargarProveedores();
        if (modo == ConsultaActionModes.CONSULTAR) {
            _producto = producto;
            lblTitle.setText("Producto Consultado");
            btnCrear.setText("Aceptar");
            jPanel1.remove(btnCancelar);
            jPanel1.revalidate();
            jPanel1.repaint();
            establecerNoEditableTodo();
            rellenarDatos();
        } else if (modo == ConsultaActionModes.ACTUALIZAR) {
            _producto = producto;
            this.txtCodigo.setEditable(false);
            lblTitle.setText("Actualizar");
            this.btnCrear.setText("Actualizar");

            rellenarDatos();
        }

    }
    
    private void cargarProveedores(){
        ArrayList<Proveedor> listProveedores = ProveedorService.getAll();
        listProveedores.forEach((p)->cboxProveedor.addItem(p.getNombre()));
    }
    private void establecerNoEditableTodo() {
        txtCodigo.setEditable(false);
        txtNombre.setEditable(false);
        spnPrecioCompra.setEnabled(false);
        spnPrecioVenta.setEnabled(false);
        cboxProveedor.setEnabled(false);
        spnDisponible.setEnabled(false);
    }

    private void rellenarDatos() {
        txtCodigo.setText(_producto.getCodigo());
        txtNombre.setText(_producto.getNombre());
        spnPrecioCompra.setValue(_producto.getPrecio_Compra());
        spnPrecioVenta.setValue(_producto.getPrecio_Venta());
        cboxProveedor.setSelectedItem(_producto.getProveedor());
        spnDisponible.setValue(_producto.getDisponible());
    }
    

