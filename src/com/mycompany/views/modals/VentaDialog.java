    private void CargarTabla(ArrayList<DetalleVenta> detalles) {
        DefaultTableModel model = (DefaultTableModel) this.tblProductos.getModel();
        model.setRowCount(0);
        detalles.forEach((p) -> model.addRow(new Object[]{p.getCodigoProducto(), p.getNombreProducto(), p.getPrecio_unitario(), p.getUnidades(), p.getSubTotal()}));
    }

    private void CargarVentaConsultada() {
        txtTotal.setText("Q" + ventaConsultada.getTotal());
        total = ventaConsultada.getTotal();
        txtResponsable.setText(ventaConsultada.getResponsable());
        txtNIT.setText(ventaConsultada.getNitCliente());
        this.detalles = ventaConsultada.getDetalles();
        this.detalles.forEach(p -> System.out.println(p.getCodigoProducto()));
        CargarTabla(ventaConsultada.getDetalles());
    }

    private void CalcularTotal() {
        total = 0;
        detalles.forEach((p) -> total += p.getSubTotal());
        txtTotal.setText("Q" + total);
    }
