    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
        // TODO add your handling code here:
        if (this.modo == ConsultaActionModes.CREAR) {

            Venta venta = new Venta();
            venta.setNitCliente(txtNIT.getText());
            venta.setResponsable(txtResponsable.getText());
            venta.setResponsable_id(AppInformation.getCurrentUserId());
            venta.setTotal(total);
            if (verificarCampos()) {
                VentaService.Post(venta, detalles);
                this.setAlwaysOnTop(false);
                JOptionPane.showMessageDialog(null, "Venta creada correctamente");
                this.dispose();
            } else {
                this.setAlwaysOnTop(false);
                JOptionPane.showMessageDialog(null, "Verifique los campos");
            }
        } else if (this.modo == ConsultaActionModes.ACTUALIZAR) {
            if (verificarCampos()) {
                ventaConsultada.setDetalles(detalles);
                ventaConsultada.setNitCliente(txtNIT.getText());
                ventaConsultada.setResponsable(txtResponsable.getText());
                ventaConsultada.setResponsable_id(AppInformation.getCurrentUserId());
                ventaConsultada.setTotal(total);
                VentaService.put(ventaConsultada);
                this.setAlwaysOnTop(false);
                JOptionPane.showMessageDialog(null, "Venta creada correctamente");
                this.dispose();
            } else {
                this.setAlwaysOnTop(false);
                JOptionPane.showMessageDialog(null, "Verifique los campos");
            }
        }

    }//GEN-LAST:event_btnCrearActionPerformed
    private boolean verificarCampos() {
        //Verificar si el NIT existe
        boolean existeNIT = false;
        ClientesService clienteService = new ClientesService();
        ArrayList<Cliente> listaClientes = clienteService.consultarClientes();
        for (Cliente cliente : listaClientes) {
            if (cliente.getNIT().equals(txtNIT.getText())) {
                existeNIT = true;
            }
        }
        if (existeNIT && detalles.size() > 0) {
            return true;
        }
        System.out.println("detalles size " + detalles.size());
        return false;
    }
