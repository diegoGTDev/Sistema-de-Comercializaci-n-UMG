    private void tblShowProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblShowProductosMouseClicked
        // TODO add your handling code here:
        this.seleccionTabla = tblShowProductos.getSelectedRow();
        if (seleccionTabla >=0){
            this.productoSeleccionado = this.tblShowProductos.getValueAt(seleccionTabla, 0).toString();
            Producto p = new Producto();
            p = ProductosService.Get(this.productoSeleccionado);
            detalleCompra.setProveedor(p.getProveedor());
            detalleCompra.setCodigo_producto(p.getCodigo());
            detalleCompra.setPrecio_compra(p.getPrecio_Compra());
            detalleCompra.setProveedor_id(p.getProveedor_id());
            detalleCompra.setNombre_producto(p.getNombre());
        }
       



    }//GEN-LAST:event_tblShowProductosMouseClicked

    private void txtCodigoKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtCodigoKeyReleased
        // TODO add your handling code here:
        String text = txtCodigo.getText();
        if (text.trim().length() == 0) {
            sorter.setRowFilter(null);  // Sin filtro
        } else {
            sorter.setRowFilter(RowFilter.regexFilter("(?i)" + text));  // Filtrado
        }
    }//GEN-LAST:event_txtCodigoKeyReleased

