    private void CargarDatos() {
        try {

            DefaultTableModel model = (DefaultTableModel) this.tblShowProductos.getModel();
            model.setRowCount(0);
            ArrayList<Producto> productos = ProductosService.getAll();
            productos.forEach((p) -> model.addRow(new Object[]{p.getCodigo(), p.getNombre(), p.getDisponible(), p.getPrecio_Compra(), p.getProveedor()}));
        } catch (Exception e) {
            System.out.println(e);
        }

    }

    private void AgregarProducto(ArrayList<DetalleCompra> lista, DetalleCompra nuevoDetalle) {
        boolean productoExiste = false;
        
        nuevoDetalle.setUnidades((int) this.spnCantidad.getValue());
        // Buscar si el producto ya está en la lista
        for (DetalleCompra detalle : lista) {
            System.out.println("Detalle: " + detalle.getCodigo_producto());
            if (detalle.getCodigo_producto().equals(nuevoDetalle.getCodigo_producto())) {
                // Producto encontrado, sumamos la unidad
                System.out.println("Producto igual");
                System.out.println("Operacion: " + detalle.getUnidades() + " + " + nuevoDetalle.getUnidades());
                detalle.setUnidades(detalle.getUnidades() + nuevoDetalle.getUnidades());
                System.out.println("Nuevas unidades: " + detalle.getUnidades());
                detalle.CalcularSubTotal();
                productoExiste = true;
                break;
            }
        }

        // Si el producto no existe, lo añadimos a la lista
        if (!productoExiste) {
            nuevoDetalle.CalcularSubTotal();
            lista.add(nuevoDetalle);
        }
    }

